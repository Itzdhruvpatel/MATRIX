const LANG_KEY = "matrix-lang";
const originals = new WeakMap();
function currentLang() { try { return localStorage.getItem(LANG_KEY) || "en"; } catch { return "en"; } }
function applyLang(lang) {
  document.documentElement.lang = lang === "hi" ? "hi" : "en";
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = walk.nextNode(); n; n = walk.nextNode()) {
    if (!originals.has(n)) {
      const key = n.textContent.replace(/\s+/g, " ").trim();
      if (!HI[key]) continue;
      originals.set(n, n.textContent);
    }
    const en = originals.get(n), key = en.replace(/\s+/g, " ").trim();
    n.textContent = lang === "hi" ? en.replace(key, HI[key]) : en;
  }
}
function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* private window: this visit only */ }
  applyLang(lang);
}
